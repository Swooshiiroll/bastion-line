// The balance master's tool (issue #75, design/balance_master.md). Run from the project folder after editing
// design/balance.md:   node tools/balance.mjs          then node tools/tree_rework_data.mjs (the game data)
// It rewrites balance.md's generated (=) columns and summary tables, and copies the tower prices into
// design/upgrade_trees_rework.md (the trees page shows them; edit them in balance.md). --check exits non-zero instead if
// either file is out of date (tools/dev.sh check runs it).
import { writeFileSync } from "node:fs";
import { BALANCE, TREES, read, parseTowers, parseTrees, cells, rowLine, nodeId, applyNode, NODE_IDS } from "./balance_lib.mjs";

const errors = [];
const balance = read(BALANCE);
const trees = read(TREES);
const towers = parseTowers(balance, errors);
const names = parseTrees(trees);

// --- Paper DPS (balance.md, Formulas): its main attack's damage per second over every target it hits, no armour,
// splash, crits, burns or boosts.
function paperDps(s) {
  if (s.orbit !== undefined) {
    // CAS Gunship: the light gun, the autocannon and the missiles (a volley of ms_volley every third pulse).
    let d = (s.damage || 0) * (s.rate || 0);
    if (s.ac_damage) d += s.ac_damage * (s.ac_rate || 0);
    if (s.ms_damage) d += s.ms_damage * (s.ms_rate || 0) * ((s.ms_volley || 1) + 2) / 3;
    return d;
  }
  if (!s.damage) return null;
  if (s.ramp !== undefined) return s.damage * s.ramp * (1 + (s.beam_power ?? 0.4) * ((s.beams || 1) - 1));
  if (!s.rate) return null;
  let shots = 1;
  if (s.jumps !== undefined) {
    const keep = 1 - (s.falloff ?? 0.15);
    shots = 0;
    for (let k = 0; k <= s.jumps; k++) shots += Math.pow(keep, k);
  } else if (s.missiles) shots = s.missiles;
  else if ((s.multishot || 1) > 1) shots = s.multishot;
  else if (s.side_gun) shots = 1 + s.side_gun;
  else if (s.drones) shots = s.drones;
  return s.damage * s.rate * shots;
}

// Each node's derived values: { id: { name, dps, spent } }, composed as the Codex shows the tree (the Retrofit on the
// stock tower; a path's steps in order on the stock tower).
function derive(slug, t) {
  const out = {};
  const nm = Object.fromEntries((names[slug]?.rows || []).map((r) => [r.id, r.name]));
  const base = applyNode({}, t.nodes.base);
  out.base = { name: nm.base, dps: paperDps(base), spent: t.nodes.base.cost };
  for (const id of ["r1", "r2", "r3"]) {
    if (t.nodes[id]) out[id] = { name: nm[id], dps: paperDps(applyNode(base, t.nodes[id])), spent: t.nodes.base.cost + t.nodes[id].cost };
  }
  for (const k of "abc") {
    let s = base, spent = t.nodes.base.cost;
    for (const id of [k + "1", k + "2", k + "3", k + "4", k + "m"]) {
      s = applyNode(s, t.nodes[id]);
      spent += t.nodes[id].cost;
      out[id] = { name: nm[id], dps: paperDps(s), spent };
    }
  }
  return out;
}

const f1 = (v) => (v === null || v === undefined ? "-" : v.toFixed(1));
const f2 = (v) => (v === null || v === undefined ? "-" : v.toFixed(2));
const derived = {};
for (const slug in towers) {
  if (!names[slug]) errors.push(`${slug}: not in upgrade_trees_rework.md`);
  derived[slug] = derive(slug, towers[slug]);
}

// --- Rewrite balance.md: derived cells in every tower table, and the tower summary.
let cur = "";
const outLines = [];
let inTowers = false;
let col = null;
for (const line of balance.split("\n")) {
  if (line.startsWith("## ")) inTowers = line === "## Towers";
  if (inTowers && line.startsWith("### ")) cur = line.slice(4).trim().split(/\s/)[0];
  if (inTowers && /^\| Node \|/.test(line)) col = Object.fromEntries(cells(line).map((h, i) => [h, i]));
  const c = cells(line);
  if (inTowers && col && line.startsWith("|") && NODE_IDS.includes(c[col.Node]) && derived[cur]?.[c[col.Node]]) {
    const d = derived[cur][c[col.Node]];
    if (col["=Name"] !== undefined) c[col["=Name"]] = d.name || "?";
    if (col["=DPS"] !== undefined) c[col["=DPS"]] = f1(d.dps);
    if (col["=Spent"] !== undefined) c[col["=Spent"]] = String(d.spent);
    if (col["=DPS/100cr"] !== undefined) c[col["=DPS/100cr"]] = d.dps === null ? "-" : f2((d.dps / d.spent) * 100);
    outLines.push(rowLine(c));
    continue;
  }
  outLines.push(line);
}
let newBalance = outLines.join("\n");
const START = "<!-- tower summary: generated by tools/balance.mjs -->";
const END = "<!-- /tower summary -->";
const sum = [START, "", "| Tower | Stock cr | Stock =DPS | A mastery: cr / =DPS | B mastery: cr / =DPS | C mastery: cr / =DPS |", "|---|---|---|---|---|---|"];
for (const slug in derived) {
  const d = derived[slug];
  sum.push(rowLine([`${names[slug]?.name || slug}`, String(d.base.spent), f1(d.base.dps), ...["am", "bm", "cm"].map((m) => `${d[m].spent} / ${f1(d[m].dps)}`)]));
}
sum.push("", END);
const a = newBalance.indexOf(START), b = newBalance.indexOf(END);
if (a < 0 || b < 0) errors.push("balance.md: the tower summary markers are missing");
else newBalance = newBalance.slice(0, a) + sum.join("\n") + newBalance.slice(b + END.length);

// --- Mirror prices into upgrade_trees_rework.md (the build price in each header, the Cost column in each table).
let slug = null;
const newTrees = trees.split("\n").map((line) => {
  const idm = line.match(/(?:^| )id: ([a-z_]+)(?: ·|$)/);
  if (idm && !line.startsWith("|")) {
    slug = idm[1];
    const t = towers[slug];
    return t ? line.replace(/build: \d+ cr/, `build: ${t.nodes.base.cost} cr`) : line;
  }
  const c = cells(line);
  if (slug && towers[slug] && c.length === 7 && /^(\d|M)$/.test(c[0])) {
    const n = towers[slug].nodes[nodeId(c[0], c[1])];
    if (!n) { errors.push(`${slug}: trees row ${c[0]} ${c[1]} has no node in balance.md`); return line; }
    c[3] = String(n.cost);
    return rowLine(c);
  }
  return line;
}).join("\n");

if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
if (process.argv.includes("--check")) {
  const stale = [];
  if (newBalance !== balance) stale.push("design/balance.md (derived columns)");
  if (newTrees !== trees) stale.push("design/upgrade_trees_rework.md (prices)");
  if (stale.length) { console.error(`stale: ${stale.join(", ")}: run node tools/balance.mjs`); process.exit(1); }
  console.log("balance.md is current");
} else {
  writeFileSync(BALANCE, newBalance);
  writeFileSync(TREES, newTrees);
  console.log(`balance.md: ${Object.keys(towers).length} towers updated; prices copied to upgrade_trees_rework.md`);
}
